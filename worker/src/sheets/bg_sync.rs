/// Write check-in columns (checked_in_at, checked_in_by, claim_token) to Sheet.
/// The timestamp is generated by the caller so the response doesn't wait for this.
#[allow(clippy::too_many_arguments)]
pub async fn mark_checked_in(
    state: AppState,
    row_index: usize,
    staff_email: String,
    claim_token: String,
    mapping: ColumnMapping,
    sheet_id: String,
    sheet_name: String,
    kv: Option<KvStore>,
    timestamp: String,
) {
    let access_token = match get_cached_access_token(&state, kv.as_ref()).await {
        Ok(t) => t,
        Err(e) => {
            tracing::error!(error = %e, "bg_sync mark_checked_in: failed to get access token");
            return;
        }
    };

    use event_checkin_domain::models::attendee::ColumnKey as CK;

    let col_checked_in_at = mapping.column_letter(CK::CheckedInAt);
    let col_checked_in_by = mapping.column_letter(CK::CheckedInBy);
    let col_claim_token = mapping.column_letter(CK::ClaimToken);

    let data = vec![
        ValueRange {
            range: format!("{sheet_name}!{col_checked_in_at}{row_index}"),
            values: vec![vec![timestamp.clone()]],
        },
        ValueRange {
            range: format!("{sheet_name}!{col_checked_in_by}{row_index}"),
            values: vec![vec![staff_email.clone()]],
        },
        ValueRange {
            range: format!("{sheet_name}!{col_claim_token}{row_index}"),
            values: vec![vec![claim_token.clone()]],
        },
    ];

    let url =
        format!("https://sheets.googleapis.com/v4/spreadsheets/{sheet_id}/values:batchUpdate");

    let body = BatchUpdateRequest {
        data,
        value_input_option: "USER_ENTERED".to_string(),
    };

    if let Err(e) = batch_update_sheet(&url, &body, &access_token).await {
        tracing::error!(
            row_index = row_index,
            error = %e,
            "bg_sync mark_checked_in: sheet write failed"
        );
        return;
    }

    tracing::info!(
        row_index = row_index,
        staff_email = %staff_email,
        claim_token = %claim_token,
        "bg_sync: marked row as checked in"
    );

    invalidate_column_map_cache(kv.as_ref(), &sheet_id, &sheet_name).await;
}

