//! Background Google Sheets sync — fire-and-forget writes via `wait_until()`.
//!
//! Each function is a standalone async task that owns all its data (no borrows
//! on the handler's stack frame). Handlers prepare the data, hand it off to
//! `ctx.wait_until()`, and return immediately.
//!
//! All functions are best-effort: errors are logged but never propagate to the
//! HTTP response. D1 is the source of truth; Sheets is a legacy mirror.

use event_checkin_domain::models::attendee::ColumnMapping;
use worker::KvStore;

use crate::http::{BatchUpdateRequest, ValueRange, batch_update_sheet};
use crate::state::AppState;

use super::{get_cached_access_token, invalidate_column_map_cache};

