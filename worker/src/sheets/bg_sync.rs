/// Append a new attendee row to Google Sheet.
#[allow(clippy::too_many_arguments)]
pub async fn append_attendee_row(
    state: AppState,
    api_id: String,
    name: String,
    first_name: String,
    last_name: String,
    email: String,
    claim_token: String,
    participation_type: String,
    registration_date: String,
    contact_channel: Option<String>,
    contact_handle: Option<String>,
    deposit_agreed: bool,
    consent_given: bool,
    photo_consent_given: bool,
    consent_marketing: Option<bool>,
    mapping: ColumnMapping,
    sheet_id: String,
    sheet_name: String,
    kv: Option<KvStore>,
) {
    let access_token = match get_cached_access_token(&state, kv.as_ref()).await {
        Ok(t) => t,
        Err(e) => {
            tracing::error!(error = %e, "bg_sync append_attendee_row: failed to get access token");
            return;
        }
    };

    use event_checkin_domain::models::attendee::ColumnKey as CK;

    let row_len = mapping.total_columns.max(31);
    let mut row = vec![String::new(); row_len];

    let set = |row: &mut Vec<String>, key: CK, val: String| {
        let idx = mapping.get_or_default(key);
        if idx < row.len() {
            row[idx] = val;
        }
    };

    set(&mut row, CK::ApiId, api_id.clone());
    set(&mut row, CK::Name, name.clone());
    set(&mut row, CK::FirstName, first_name);
    set(&mut row, CK::LastName, last_name);
    set(&mut row, CK::Email, email.clone());
    set(&mut row, CK::TicketName, "Self-Registered".to_string());
    set(&mut row, CK::RegistrationDate, registration_date);
    set(&mut row, CK::ApprovalStatus, "Approved".to_string());
    set(&mut row, CK::ClaimToken, claim_token);
    set(&mut row, CK::ParticipationType, participation_type);
    if let Some(channel) = contact_channel {
        set(&mut row, CK::ContactChannel, channel);
    }
    if let Some(handle) = contact_handle {
        set(&mut row, CK::ContactHandle, handle);
    }
    if deposit_agreed {
        set(&mut row, CK::DepositAgreed, "Yes".to_string());
    }
    if consent_given {
        set(&mut row, CK::ConsentGiven, "Yes".to_string());
    }
    if photo_consent_given {
        set(&mut row, CK::PhotoConsent, "Yes".to_string());
    }
    if consent_marketing.unwrap_or(false) {
        set(&mut row, CK::ConsentMarketing, "Yes".to_string());
    }

    let last_col_idx = row.iter().rposition(|v| !v.is_empty()).unwrap_or(0);
    let last_col_letter = {
        let mut result = String::new();
        let mut n = last_col_idx;
        loop {
            result.insert(0, (b'A' + (n % 26) as u8) as char);
            if n < 26 {
                break;
            }
            n = (n / 26) - 1;
        }
        result
    };

    row.truncate(last_col_idx + 1);

    let url = format!(
        "https://sheets.googleapis.com/v4/spreadsheets/{sheet_id}/values/{}!A:{last_col_letter}:append?valueInputOption=USER_ENTERED&insertDataOption=INSERT_ROWS",
        urlencoding::encode(&sheet_name)
    );

    let body = crate::http::ValueRange {
        range: format!("{sheet_name}!A:{last_col_letter}"),
        values: vec![row],
    };

    if let Err(e) =
        crate::http::post_json::<serde_json::Value>(&url, &body, Some(&access_token)).await
    {
        tracing::error!(
            %api_id,
            %email,
            error = %e,
            "bg_sync append_attendee_row: sheet write failed"
        );
        return;
    }

    tracing::info!(
        %api_id,
        %email,
        "bg_sync: appended self-registration row to google sheet"
    );

    invalidate_column_map_cache(kv.as_ref(), &sheet_id, &sheet_name).await;
}

